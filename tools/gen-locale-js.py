"""Turn locales/<lang>/odina.ftl into locales.js for the static pages.

The preview and the signing page are plain HTML with no build step and no
network: opening the file must work from disk. So the strings have to be in
the repository, and the only honest way to do that is to generate them from
the same .ftl files a reviewer edits — a second hand-kept copy would drift.

    python3 tools/gen-locale-js.py            # write locales.js
    python3 tools/gen-locale-js.py --check    # fail if it is stale

A draft language is marked in ODINA_DRAFT so a page can label it. It is never
hidden: a reviewer has to read it to reject it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALES = ROOT / "locales"

# The order the language picker shows: shipped first, then reviewed drafts.
ORDER = ["ar", "en", "zh-Hans", "ja", "es", "ru", "hi", "de", "fr", "pt-BR"]
DRAFT = {"de", "fr", "pt-BR"}


def parse_ftl(path: Path) -> dict[str, str]:
    """Return key -> value. Fluent attributes and multiline values are joined."""
    out: dict[str, str] = {}
    key: str | None = None
    buf: list[str] = []

    def flush() -> None:
        nonlocal key, buf
        if key is not None:
            out[key] = "".join(buf).strip()
        key, buf = None, []

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.rstrip()
        if not line.strip() or line.lstrip().startswith("#"):
            flush()
            continue
        if not line[0].isspace() and "=" in line:
            flush()
            key, _, first = line.partition("=")
            key = key.strip()
            buf = [first.strip()]
        elif key is not None:
            buf.append(line.strip())
    flush()
    return out


def build() -> tuple[str, dict[str, int]]:
    strings: dict[str, dict[str, str]] = {}
    counts: dict[str, int] = {}
    for lang in ORDER:
        path = LOCALES / lang / "odina.ftl"
        if not path.is_file():
            raise SystemExit(f"gen-locale-js: missing {path.relative_to(ROOT)}")
        table = parse_ftl(path)
        strings[lang] = table
        counts[lang] = len(table)

    payload = (
        "/* SPDX-License-Identifier: AGPL-3.0-or-later */\n"
        "/* Copyright (c) 2026 bifa90 — Odina */\n"
        "/* Generated by tools/gen-locale-js.py — do not edit by hand.\n"
        "   Source of truth: locales/<lang>/odina.ftl (edit those, then regenerate). */\n"
        f"window.ODINA_STRINGS = {json.dumps(strings, ensure_ascii=False, sort_keys=True, indent=0)};\n"
        f"window.ODINA_DRAFT = {json.dumps(sorted(DRAFT))};\n"
        f"window.ODINA_ORDER = {json.dumps(ORDER)};\n"
    )
    return payload, counts


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if locales.js is stale")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    payload, counts = build()
    target = ROOT / "locales.js"

    if args.check:
        old = target.read_text(encoding="utf-8") if target.is_file() else ""
        if old != payload:
            print("gen-locale-js: locales.js is stale — run python3 tools/gen-locale-js.py",
                  file=sys.stderr)
            return 1
        if not args.quiet:
            print(f"gen-locale-js: current · {len(counts)} languages")
        return 0

    target.write_text(payload, encoding="utf-8")
    if not args.quiet:
        detail = " · ".join(f"{k}:{v}" for k, v in counts.items())
        print(f"wrote locales.js · {len(counts)} languages\n  {detail}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
