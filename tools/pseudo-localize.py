"""Pseudo-localisation — the layout test that runs before a user sees it.

§3.9.5 requires that every UI string survive +40% length, widened glyphs and
RTL without clipping. Doing that on the real translations catches only the
languages that happen to be long; this builds an extreme locale on purpose.

What it produces, under locales/qps/:
  odina.ftl      every message wrapped in pseudo glyphs, +40% padded
  REPORT.md      per-key growth, and the keys most likely to clip

What it does NOT do: render. That needs a browser, so the workflow runs
`--check` (structure + growth budget) and the visual pass stays a manual
step in the review gate (§36).

Usage:
    python3 tools/pseudo-localize.py [--root .] [--source ar] [--check]
                                     [--growth 1.4]

Exit codes: 0 = ok, 1 = a key exceeds the budget, 2 = bad input.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Glyphs chosen to stress width and diacritics: the widest Latin letters plus
# combining marks. No CJK on purpose — CJK is narrower per word and would make
# the test lie in the other direction.
WIDE = "ẞǄǅǱǲǳǷȜȝĜĞĠĢŴŶŸƁƇƊƑƓƗƘȤȥⱣⱤ"
ACCENT = "̀́̂̃̄̆̇̈̉̊̋̌̏̑̒̓̔̽"

GLYPH_MAP = {
    "a": "á", "e": "é", "i": "î", "o": "ô", "u": "û",
    "A": "Á", "E": "É", "I": "Î", "O": "Ô", "U": "Û",
}

KEY_RE = re.compile(r"^([A-Za-z0-9_.\-]+)\s*=\s*(.*)$")
VAR_RE = re.compile(r"\{\s*\$[A-Za-z0-9_]+\s*\}")


def pseudo(text: str, growth: float) -> str:
    """Wrap, accent, and pad a message while protecting { $vars }."""
    if not text.strip():
        return text

    # Split on variables so they stay byte-identical for the parser.
    parts: list[str] = []
    pos = 0
    for m in VAR_RE.finditer(text):
        parts.append(text[pos:m.start()])
        parts.append(m.group(0))
        pos = m.end()
    parts.append(text[pos:])

    out: list[str] = []
    for part in parts:
        if VAR_RE.fullmatch(part):
            out.append(part)
            continue
        accented = "".join(GLYPH_MAP.get(ch, ch) for ch in part)
        out.append(accented)

    body = "".join(out)
    # Pad with wide glyphs to the growth target, keeping a bracketed marker so
    # clipping is obvious at a glance.
    target = int(len(text) * growth)
    pad_needed = max(target - len(body), 0)
    if pad_needed:
        filler = "".join(WIDE[i % len(WIDE)] for i in range(pad_needed))
        body = f"⟦{body}{filler}⟧"
    else:
        body = f"⟦{body}⟧"
    return body


def read_source(path: Path) -> dict[str, str]:
    entries: dict[str, str] = {}
    current: str | None = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        m = KEY_RE.match(raw)
        if m and not raw.startswith((" ", "\t")):
            current = m.group(1)
            entries[current] = m.group(2)
        elif current and raw.startswith((" ", "\t")):
            entries[current] += "\n    " + raw.strip()
    return entries


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--source", default="en",
                    help="locale to pseudo-localise (en by default: longest phrases)")
    ap.add_argument("--growth", type=float, default=1.4)
    ap.add_argument("--quiet", action="store_true", help="suppress success output")
    ap.add_argument("--check", action="store_true",
                    help="verify only; do not write locales/qps/")
    args = ap.parse_args()

    root = Path(args.root)
    src = root / "locales" / args.source / "odina.ftl"
    if not src.exists():
        print(f"pseudo: source locale not found: {src}", file=sys.stderr)
        return 2

    entries = read_source(src)
    if not entries:
        print("pseudo: no messages parsed", file=sys.stderr)
        return 2

    out_dir = root / "locales" / "qps"
    lines: list[str] = [
        "# AUTO-GENERATED by tools/pseudo-localize.py — do not edit.",
        f"# source: locales/{args.source}/odina.ftl · growth target: {args.growth}x",
        "",
    ]
    rows: list[tuple[str, int, int, float]] = []
    over_budget: list[str] = []

    for key, value in entries.items():
        conv = pseudo(value, args.growth)
        lines.append(f"{key} = {conv}")
        growth = len(conv) / max(len(value), 1)
        rows.append((key, len(value), len(conv), growth))
        if growth < args.growth:
            over_budget.append(key)

    report = ["# Pseudo-localisation report", "",
              f"- source: `locales/{args.source}/odina.ftl`",
              f"- keys: **{len(entries)}**",
              f"- growth target: **{args.growth}x**", "",
              "| key | source chars | pseudo chars | growth |",
              "|-----|--------------|--------------|--------|"]
    for key, a, b, g in rows:
        report.append(f"| `{key}` | {a} | {b} | {g:.2f}x |")

    report += ["", "## How to use this", "",
               "1. Run the app or `ui-preview.html` with `qps` selected.",
               "2. Any clipped label, wrapped button or overflowing row is a defect.",
               "3. Fix the layout, not the translation — the translation is real.",
               "4. Re-run this tool after every new key."]

    if args.check:
        missing = [k for k, _, _, g in rows if g < args.growth]
        if missing:
            print(f"pseudo: {len(missing)} key(s) below the growth target: "
                  f"{', '.join(missing[:5])}", file=sys.stderr)
            return 1
        if not args.quiet:
            print(f"pseudo: {len(rows)} key(s) expanded to {args.growth}x or more")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "odina.ftl").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (out_dir / "REPORT.md").write_text("\n".join(report) + "\n", encoding="utf-8")

    if not args.quiet:
        print(f"pseudo: wrote {out_dir/'odina.ftl'} ({len(entries)} keys)")
        print(f"pseudo: wrote {out_dir/'REPORT.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
